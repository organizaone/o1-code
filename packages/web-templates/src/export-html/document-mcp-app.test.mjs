import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { JSDOM } from 'jsdom';

test('exported MCP results remain readable without an app bridge', async () => {
  const generated = await readFile(
    new URL(
      '../generated/exportTranscriptDocumentTemplate.ts',
      import.meta.url,
    ),
    'utf8',
  );
  const match = generated.match(
    /EXPORT_TRANSCRIPT_RENDERER_VERSION = "([^"]+)"/,
  );
  assert.ok(match, 'renderer version must be generated by the build');
  const renderer = await readFile(
    new URL('./dist/export-transcript-document.js', import.meta.url),
    'utf8',
  );
  const document = {
    schemaVersion: 1,
    rendererVersion: match[1],
    blocks: [
      {
        id: 'tool-1',
        kind: 'tool',
        toolCallId: 'call-1',
        title: 'MCP result',
        toolName: 'mcp_demo',
        status: 'completed',
        preview: { kind: 'generic' },
        resultPreview: { kind: 'text', text: 'MCP fallback remains readable' },
        rawOutput: {
          type: 'mcp_app',
          serverName: 'demo',
          resourceUri: 'ui://demo',
          html: '<p>UNSAFE_APP</p>',
          fallbackText: 'MCP fallback remains readable',
          toolResult: { content: [] },
          toolArguments: {},
        },
        createdAt: 1,
        updatedAt: 1,
        clientReceivedAt: 1,
      },
    ],
    metadata: {
      exportedAt: '2026-10-29T00:00:00Z',
      complete: true,
      truncated: false,
    },
  };
  const dom = new JSDOM(
    `<!doctype html><html><body><div id="app"></div><script id="transcript-document" type="application/json">${JSON.stringify(document)}</script></body></html>`,
    {
      url: 'https://example.test/',
      runScripts: 'dangerously',
      pretendToBeVisual: true,
    },
  );
  try {
    dom.window.TextEncoder = TextEncoder;
    dom.window.ResizeObserver = class {
      observe() {}
      unobserve() {}
      disconnect() {}
    };
    dom.window.eval(renderer);
    for (let attempt = 0; attempt < 50; attempt++) {
      if (
        dom.window.document
          .querySelector('#app')
          ?.textContent.includes('MCP fallback remains readable')
      )
        break;
      await new Promise((resolve) => setTimeout(resolve, 20));
    }
    const { body } = dom.window.document;
    assert.match(
      body.querySelector('#app')?.textContent ?? '',
      /MCP fallback remains readable/,
    );
    assert.equal(body.querySelector('iframe'), null);
    assert.equal(body.textContent.includes('UNSAFE_APP'), true); // only the inert JSON envelope
    assert.equal(
      body.querySelector('#app')?.textContent.includes('UNSAFE_APP'),
      false,
    );
  } finally {
    dom.window.close();
  }
});
